
CREATE TABLE cliente (
    id_cliente     integer GENERATED BY DEFAULT AS IDENTITY,
    nome           varchar(100) NOT NULL,
    email          varchar(120) NOT NULL,
    cidade         varchar(60)  NOT NULL,
    data_cadastro  date         NOT NULL DEFAULT current_date,
    CONSTRAINT pk_cliente PRIMARY KEY (id_cliente),
    CONSTRAINT uq_cliente_email UNIQUE (email)
);

CREATE TABLE produto (
    id_produto  integer GENERATED BY DEFAULT AS IDENTITY,
    nome        varchar(100) NOT NULL,
    preco       numeric(10,2) NOT NULL,
    estoque     integer NOT NULL DEFAULT 0,
    CONSTRAINT pk_produto PRIMARY KEY (id_produto),
    CONSTRAINT ck_produto_preco CHECK (preco > 0),
    CONSTRAINT ck_produto_estoque CHECK (estoque >= 0)
);

CREATE TABLE pedido (
    id_pedido    integer GENERATED BY DEFAULT AS IDENTITY,
    id_cliente   integer NOT NULL,
    data_pedido  timestamp NOT NULL DEFAULT current_timestamp,
    status       varchar(15) NOT NULL DEFAULT 'ABERTO',
    CONSTRAINT pk_pedido PRIMARY KEY (id_pedido),
    CONSTRAINT fk_pedido_cliente FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente),
    CONSTRAINT ck_pedido_status CHECK (status IN ('ABERTO', 'FINALIZADO', 'CANCELADO'))
);

CREATE TABLE item_pedido (
    id_item_pedido  integer GENERATED BY DEFAULT AS IDENTITY,
    id_pedido       integer NOT NULL,
    id_produto      integer NOT NULL,
    quantidade      integer NOT NULL,
    preco_unitario  numeric(10,2) NOT NULL,
    CONSTRAINT pk_item_pedido PRIMARY KEY (id_item_pedido),
    CONSTRAINT fk_item_pedido_pedido FOREIGN KEY (id_pedido)
        REFERENCES pedido (id_pedido),
    CONSTRAINT fk_item_pedido_produto FOREIGN KEY (id_produto)
        REFERENCES produto (id_produto),
    CONSTRAINT ck_item_pedido_quantidade CHECK (quantidade > 0),
    CONSTRAINT ck_item_pedido_preco_unitario CHECK (preco_unitario > 0),
    CONSTRAINT uq_item_pedido_pedido_produto UNIQUE (id_pedido, id_produto)
);

CREATE OR REPLACE FUNCTION fn_baixar_estoque()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_estoque integer;
    v_nome    varchar(100);
BEGIN
    SELECT estoque, nome
      INTO v_estoque, v_nome
      FROM produto
     WHERE id_produto = NEW.id_produto
       FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Produto % nao encontrado', NEW.id_produto;
    END IF;

    IF v_estoque < NEW.quantidade THEN
        RAISE EXCEPTION 'Estoque insuficiente para o produto % (%): disponivel %, solicitado %',
            NEW.id_produto, v_nome, v_estoque, NEW.quantidade;
    END IF;

    UPDATE produto
       SET estoque = estoque - NEW.quantidade
     WHERE id_produto = NEW.id_produto;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_item_pedido_bi
BEFORE INSERT ON item_pedido
FOR EACH ROW
EXECUTE FUNCTION fn_baixar_estoque();


CREATE OR REPLACE FUNCTION fn_total_pedido(p_id_pedido integer)
RETURNS numeric
LANGUAGE sql
AS $$
    SELECT coalesce(sum(quantidade * preco_unitario), 0)
      FROM item_pedido
     WHERE id_pedido = p_id_pedido;
$$;


CREATE OR REPLACE VIEW vw_resumo_pedido AS
SELECT p.id_pedido,
       c.nome   AS nome_cliente,
       c.cidade,
       p.data_pedido,
       p.status,
       coalesce(sum(i.quantidade), 0)                    AS qtd_itens,
       coalesce(sum(i.quantidade * i.preco_unitario), 0) AS total_pedido
  FROM pedido p
  JOIN cliente c ON c.id_cliente = p.id_cliente
  LEFT JOIN item_pedido i ON i.id_pedido = p.id_pedido
 GROUP BY p.id_pedido, c.nome, c.cidade, p.data_pedido, p.status;
